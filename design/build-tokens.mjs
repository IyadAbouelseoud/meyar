#!/usr/bin/env node
// Builds design/tokens.css from design/tokens.json and checks every contrast pair.
// Usage: node design/build-tokens.mjs          (build + check, exit 1 on any failure)
//        node design/build-tokens.mjs --check  (check only, write nothing)
// No dependencies. Contrast maths: WCAG 2.2 relative luminance and contrast ratio.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));
const checkOnly = process.argv.includes('--check');

const get = (path) => path.split('.').reduce((o, k) => (o == null ? o : o[k]), t);
const resolve = (v, seen = new Set()) => {
  if (typeof v !== 'string') return v;
  const m = v.match(/^\{(.+)\}$/);
  if (!m) return v;
  if (seen.has(m[1])) throw new Error(`Reference cycle at ${m[1]}`);
  seen.add(m[1]);
  const node = get(m[1]);
  if (!node || node.$value === undefined) throw new Error(`Unresolved reference ${v}`);
  return resolve(node.$value, seen);
};
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

// ---- contrast
const hex = (h) => { h = h.replace('#', ''); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255); };
const lum = (h) => { const [r, g, b] = hex(h).map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

let failures = 0;
const report = [];
for (const theme of ['paper', 'instrument']) {
  for (const [fg, bg, min] of t.contrastPairs.pairs) {
    const a = resolve(t.semantic[theme][fg].$value), b = resolve(t.semantic[theme][bg].$value);
    const r = ratio(a, b);
    const ok = r >= min;
    if (!ok) failures++;
    report.push(`${ok ? 'PASS' : 'FAIL'}  ${theme.padEnd(10)} ${fg.padEnd(13)} on ${bg.padEnd(9)} ${r.toFixed(2).padStart(5)}:1  (min ${min})  ${a} / ${b}`);
  }
}
console.log(report.join('\n'));
console.log(`\n${report.length - failures}/${report.length} contrast pairs pass.`);

if (!checkOnly) {
  const L = [];
  L.push('/* GENERATED by design/build-tokens.mjs from design/tokens.json — do not edit by hand. */');
  L.push(':root {');
  for (const [fam, shades] of Object.entries(t.primitive.color))
    for (const [k, v] of Object.entries(shades)) L.push(`  --m-p-${kebab(fam)}-${kebab(k)}: ${v.$value};`);
  for (const [k, v] of Object.entries(t.font)) L.push(`  --m-font-${k}: ${v.$value};`);
  for (const [k, v] of Object.entries(t.size)) if (!k.startsWith('$')) L.push(`  --m-size-${k}-base: ${v.$value};`);
  for (const [k, v] of Object.entries(t.leading)) L.push(`  --m-leading-${kebab(k)}: ${v.$value};`);
  for (const [k, v] of Object.entries(t.space)) L.push(`  --m-space-${k}: ${v.$value};`);
  for (const [k, v] of Object.entries(t.radius)) if (!k.startsWith('$')) L.push(`  --m-radius-${k}: ${v.$value};`);
  for (const [k, v] of Object.entries(t.target)) L.push(`  --m-target-${k}: ${v.$value};`);
  for (const [k, v] of Object.entries(t.motion.ease)) L.push(`  --m-ease-${k}: ${v.$value};`);
  for (const [k, v] of Object.entries(t.motion.duration)) L.push(`  --m-dur-${k}: ${v.$value};`);
  L.push('  --m-elder-scale: 1;');
  L.push('  --m-target: var(--m-target-min);');
  for (const k of Object.keys(t.size)) if (!k.startsWith('$')) L.push(`  --m-size-${k}: calc(var(--m-size-${k}-base) * var(--m-elder-scale));`);
  L.push('}');
  for (const theme of ['paper', 'instrument']) {
    L.push(theme === 'paper' ? ':root, [data-theme="paper"] {' : `[data-theme="${theme}"] {`);
    L.push(`  color-scheme: ${theme === 'paper' ? 'light' : 'dark'};`);
    for (const [k, v] of Object.entries(t.semantic[theme])) if (!k.startsWith('$')) L.push(`  --m-${kebab(k)}: ${resolve(v.$value)};`);
    L.push('}');
  }
  L.push('[data-elder="on"] {');
  L.push(`  --m-elder-scale: ${t.elder.scale.$value};`);
  L.push(`  --m-leading-arabic-body: ${t.elder.leading.$value};`);
  L.push(`  --m-target: ${t.elder.target.$value};`);
  // Re-declare sizes here so elder mode works on any subtree, not only on <html>.
  for (const k of Object.keys(t.size)) if (!k.startsWith('$')) L.push(`  --m-size-${k}: calc(var(--m-size-${k}-base) * var(--m-elder-scale));`);
  L.push('}');
  writeFileSync(join(here, 'tokens.css'), L.join('\n') + '\n');
  console.log('Wrote design/tokens.css');
}
process.exit(failures ? 1 : 0);
